def _spaced(n):
    """The project's thousands form: `18724` -> `18 724`."""
    out = str(n)
    parts = []
    while len(out) > 3:
        parts.insert(0, out[-3:])
        out = out[:-3]
    parts.insert(0, out)
    return " ".join(parts)


def trial_the_blocking_numbers_are_the_ones_the_documents_state():
    """R6 clause 3 from the enforcing side: this file computes, the note reports.

    *"Where a document states a quantity that a trial also computes, the trial's
    value is the enforced one."* `README-l5 §4`'s dated non-capability note carries
    the numbers this file measures — the form `README-l4 §4` took for the 26‰ cue
    reach one layer down — so the note is checked against the run rather than
    trusted, and a drift in either direction is a red trial rather than a diff
    nobody reads.

    The class index is checked for the same reason `strain/l5`'s existing file
    checks its own: a README that names a file which does not exist, or omits one
    that does, has stopped being a record.
    """
    here = os.path.dirname(os.path.abspath(__file__))
    index = os.path.join(os.path.dirname(here), "README.md")
    with open(index, "r", encoding="utf-8") as fh:
        text = fh.read()
    require("l5/t_prospection_blocking_seam.py" in text,
            "trials/strain/README.md does not index this file")
    require(os.path.isfile(os.path.join(here,
                                        "t_prospection_blocking_seam.py")),
            "the indexed strain file is not where the index says it is")

    state, _budget, b = _at_the_gate()
    reached, answerable, permille = _reach()
    tiers = len(l5.pending_iids(state)) + len(l5.fired_iids(state))

    readme = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(here))),
                          "core", "layers", "README-l5.md")
    with open(readme, "r", encoding="utf-8") as fh:
        note = fh.read()
    for figure in ("%s of %s" % (_spaced(reached), _spaced(answerable)),
                   "%d‰" % (permille,),
                   _spaced(len(l5.fired_iids(state))),
                   _spaced(len(l5.pending_iids(state))),
                   _spaced(tiers)):
        require(figure in note,
                "core/layers/README-l5.md does not carry the measured figure "
                "%r. Under R6 clause 3 this trial's value is the enforced one "
                "and the note is what has to say it: cue reach %s of %s = %d‰, "
                "over %s prospection-tier events none of which any cue reaches"
                % (figure, _spaced(reached), _spaced(answerable), permille,
                   _spaced(tiers)))
